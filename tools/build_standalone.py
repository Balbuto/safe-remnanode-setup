#!/usr/bin/env python3
"""Build/check the self-contained installer from lib/ and vendor/rkn-watcher/."""
import argparse
import base64
import gzip
import hashlib
import io
import pathlib
import re
import sys
import tarfile
import textwrap

ROOT = pathlib.Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'vendor' / 'rkn-watcher'
VENDOR_FILES = (
    'LICENSE', 'UPSTREAM_COMMIT', 'VERSION', 'config_tool.py', 'geoip_apply.py', 'installer.sh',
    *(f'lib/{name}.sh' for name in ('cli', 'common', 'config', 'firewall', 'lists', 'services', 'snapshots', 'ui')),
    'rkn-watcher.sh',
)
RKN_EXECUTABLES = {'config_tool.py', 'geoip_apply.py', 'installer.sh', 'rkn-watcher.sh'}
MARKER = '# @rkn-bundle@'
HEADER = '''#!/bin/bash
# Generated by tools/build_standalone.py. Edit lib/ and vendor/ instead.
REMNA_SOURCE_ROOT=''
'''
FOOTER = '''if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then main "$@"; fi
'''


def manifest_bytes(files):
    return ''.join(f'{hashlib.sha256(files[name]).hexdigest()}  {name}\n' for name in VENDOR_FILES).encode('ascii')


def vendor_files():
    expected = {*VENDOR_FILES, 'SHA256SUMS'}
    present = {p.relative_to(VENDOR).as_posix() for p in VENDOR.rglob('*') if not p.is_dir() or p.is_symlink()}
    if expected != present:
        raise ValueError(f'unexpected vendor file set: {sorted(expected ^ present)}')
    for name in expected:
        path = VENDOR / name
        if not path.is_file() or path.is_symlink():
            raise ValueError(f'not a regular vendored file: {name}')
    files = {name: (VENDOR / name).read_bytes() for name in expected}
    if files['SHA256SUMS'] != manifest_bytes(files):
        raise ValueError('vendored RKN files do not match SHA256SUMS')
    return files


def render_bundle(files):
    version = files['VERSION'].decode('ascii').strip()
    revision = files['UPSTREAM_COMMIT'].decode('ascii').strip()
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version) or not re.fullmatch(r'[0-9a-f]{40}', revision):
        raise ValueError('invalid RKN version or commit in vendor/')
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode='w', format=tarfile.USTAR_FORMAT) as tar:
        for name, data in sorted(files.items()):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o755 if name in RKN_EXECUTABLES else 0o644
            tar.addfile(info, io.BytesIO(data))
    compressed = io.BytesIO()
    with gzip.GzipFile(filename='', fileobj=compressed, mode='wb', mtime=0, compresslevel=9) as gz:
        gz.write(buf.getvalue())
    bundle = compressed.getvalue()
    payload = '\n'.join(textwrap.wrap(base64.b64encode(bundle).decode('ascii'), width=76))
    return f'''# BEGIN GENERATED RKN BUNDLE
RKN_VERSION="{version}"
RKN_UPSTREAM_REVISION="{revision}"
RKN_BUNDLE_SHA256="{hashlib.sha256(bundle).hexdigest()}"
rkn_bundle_payload() {{
    cat <<'RKN_BUNDLE_BASE64'
{payload}
RKN_BUNDLE_BASE64
}}
# END GENERATED RKN BUNDLE'''


def render():
    module_dir = ROOT / 'lib'
    names = (module_dir / 'modules.list').read_text(encoding='utf-8').splitlines()
    if not names or any(not re.fullmatch(r'[a-z]+', name) for name in names):
        raise ValueError('invalid lib/modules.list')
    if sorted(f'{name}.sh' for name in names) != sorted(p.name for p in module_dir.glob('*.sh')):
        raise ValueError('lib/modules.list does not match module files')
    sections = [HEADER]
    for name in names:
        content = (module_dir / f'{name}.sh').read_text(encoding='utf-8').split('\n', 1)[1]
        sections.append(f'# Source: lib/{name}.sh\n' + content)
    out = '\n'.join(sections) + '\n' + FOOTER
    if out.count(MARKER) != 1:
        raise ValueError('expected one RKN bundle marker')
    return out.replace(MARKER, render_bundle(vendor_files()), 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the committed standalone script is stale')
    parser.add_argument('--output', type=pathlib.Path, default=ROOT / 'safe-remnanode-setup.sh')
    args = parser.parse_args()
    try:
        output = render().encode('utf-8')
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != output:
                raise ValueError('standalone output is stale; run python3 tools/build_standalone.py')
        else:
            args.output.write_bytes(output)
            args.output.chmod(0o755)
    except (OSError, ValueError) as exc:
        print(f'Build failed: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
